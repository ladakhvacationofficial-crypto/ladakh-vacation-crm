/**
 * Filter directory properties by destination key or valley name.
 */
export function getPropertiesByDestination(destination: string): DirectoryProperty[] {
  const q = destination.trim().toLowerCase();
  if (!q || q === 'all' || q.includes('full') || q.includes('every')) {
    return MASTER_DESTINATION_HOTELS;
  }
  return MASTER_DESTINATION_HOTELS.filter((p) => {
    const text = `${p.city} ${p.settlement} ${p.valley} ${p.name}`.toLowerCase();
    if (q.includes('leh') && (text.includes('leh') || text.includes('sham'))) return true;
    if (q.includes('nubra') && text.includes('nubra')) return true;
    if (q.includes('pangong') && text.includes('pangong')) return true;
    if (q.includes('hanle') && (text.includes('hanle') || text.includes('changthang') || text.includes('moriri'))) return true;
    if (q.includes('zanskar') && (text.includes('zanskar') || text.includes('kargil'))) return true;
    if (q.includes('kargil') && (text.includes('kargil') || text.includes('zanskar'))) return true;
    if (q.includes('srinagar') && (text.includes('srinagar') || text.includes('kashmir') || text.includes('dal') || text.includes('nigeen') || text.includes('gulmarg') || text.includes('pahalgam'))) return true;
    return text.includes(q);
  });
}
